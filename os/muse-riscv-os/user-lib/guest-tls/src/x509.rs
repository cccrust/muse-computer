    fn chain_negatives() {
        let now = (1790641879 + 2106001879) / 2;
        // tampered issuer byte: parses, signature fails (issuer mismatch fires first).
        match verify_chain(TAMPERED_DER, ROOT_DER, now, [10, 0, 2, 2]) {
            Err(CertError::IssuerMismatch) | Err(CertError::BadSignature) => {}
            x => panic!("tampered: {:?}", x),
        }
        // wrong IP
        assert!(verify_chain(LEAF_DER, ROOT_DER, now, [1, 2, 3, 4]) == Err(CertError::SanMismatch));
        // expired / premature (beyond the +/-86400 slop)
        assert!(verify_chain(LEAF_DER, ROOT_DER, 2200000000, [10, 0, 2, 2]) == Err(CertError::BadValidity));
        assert!(verify_chain(LEAF_DER, ROOT_DER, 1700000000, [10, 0, 2, 2]) == Err(CertError::BadValidity));
        // role confusion
        assert!(verify_chain(ROOT_DER, ROOT_DER, now, [10, 0, 2, 2]) == Err(CertError::NotCa));
        assert!(verify_chain(LEAF_DER, LEAF_DER, now, [10, 0, 2, 2]) == Err(CertError::NotCa));
        // garbage
        assert!(parse_cert(&[0x30, 0x03, 0x01, 0x01, 0xff]).is_err());
        assert!(parse_cert(&[]).is_err());
    }
