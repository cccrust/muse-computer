// v3.14: minimal DER/X.509 for the TLS 1.3 server chain (single shape:
// ecdsa-with-SHA256 + P-256, root CA + leaf with SAN DNS+IP, as emitted
// by the registry's openssl recipe). no_std + no_alloc: the caller owns
// all buffers; parsed values borrow the input (`Cert<'a>`) or land in
// fixed arrays. Unknown NON-critical extensions are ignored; unknown
// CRITICAL extensions are rejected (RFC 5280 §4.2).

use super::n256::ecdsa_verify_raw;
use super::p256::F256;
use super::Sha256;

// ---- known OIDs (byte-exact) ----
/// ecdsa-with-SHA256 1.2.840.10045.4.3.2
const OID_ECDSA_SHA256: &[u8] = &[0x06, 0x08, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x04, 0x03, 0x02];
/// id-ecPublicKey 1.2.840.10045.2.1
const OID_EC_PUBKEY: &[u8] = &[0x06, 0x07, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02, 0x01];
/// secp256r1 1.2.840.10045.3.1.7 (first arc byte is 0x2A, not 0x2B).
const OID_SECP256R1: &[u8] = &[0x06, 0x08, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x03, 0x01, 0x07];
/// basicConstraints 2.5.29.19
const OID_BASIC: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x13];
/// keyUsage 2.5.29.15
const OID_KEYUSAGE: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x0f];
/// subjectAltName 2.5.29.17
const OID_SAN: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x11];
/// extendedKeyUsage 2.5.29.37, authorityKeyIdentifier 2.5.29.35,
/// subjectKeyIdentifier 2.5.29.14 (parsed as known, unenforced).
const OID_EKU: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x25];
const OID_AKID: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x23];
const OID_SKID: &[u8] = &[0x06, 0x03, 0x55, 0x1d, 0x0e];

#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum CertError {
    BadDer,
    BadVersion,
    BadSigAlg,
    BadSpki,
    BadSig,
    BadTime,
    BadValidity,
    NotCa,
    BadKeyUsage,
    UnknownCriticalExtension,
    IssuerMismatch,
    SanMismatch,
    BadSignature,
}

/// DER TLV: tag + header + value. `total` covers header + value.
struct Tlv<'a> {
    tag: u8,
    val: &'a [u8],
    total: &'a [u8],
}

fn read_tlv(b: &[u8]) -> Option<(Tlv<'_>, &[u8])> {
    if b.len() < 2 {
        return None;
    }
    let tag = b[0];
    let (hlen, vlen) = match b[1] {
        n if n < 0x80 => (2, n as usize),
        0x81 => {
            if b.len() < 3 {
                return None;
            }
            (3, b[2] as usize)
        }
        0x82 => {
            if b.len() < 4 {
                return None;
            }
            (4, ((b[2] as usize) << 8) | b[3] as usize)
        }
        _ => return None, // long form > 64KB: rejected (certs are ~500B)
    };
    if b.len() < hlen + vlen {
        return None;
    }
    Some((
        Tlv { tag, val: &b[hlen..hlen + vlen], total: &b[..hlen + vlen] },
        &b[hlen + vlen..],
    ))
}

/// Children of a full TLV (checks wrapper tag, consumes everything).
fn children<'a>(b: &'a [u8], tag: u8, out: &mut [&'a [u8]], raw: &mut [&'a [u8]]) -> Result<usize, CertError> {
    let (t, rest) = read_tlv(b).ok_or(CertError::BadDer)?;
    if t.tag != tag || !rest.is_empty() {
        return Err(CertError::BadDer);
    }
    children_of_value(t.val, out, raw)
}

/// Children of already-unwrapped contents (no header to check).
fn children_of_value<'a>(mut b: &'a [u8], out: &mut [&'a [u8]], raw: &mut [&'a [u8]]) -> Result<usize, CertError> {
    let mut n = 0;
    while !b.is_empty() {
        if n >= out.len() {
            return Err(CertError::BadDer);
        }
        let (c, r) = read_tlv(b).ok_or(CertError::BadDer)?;
        out[n] = c.val;
        raw[n] = c.total;
        n += 1;
        b = r;
    }
    Ok(n)
}

/// INTEGER -> exactly 32 bytes. Strips redundant leading zeros and the one
/// DER sign zero (a 32-byte value may legitimately have its high bit set:
/// r/s < n < 2^256; range is enforced downstream by ecdsa_verify_raw).
fn int32(v: &[u8], out: &mut [u8; 32]) -> Result<(), CertError> {
    let mut b = v;
    // redundant zeros (next byte's high bit clear); then at most one sign zero
    while b.len() > 1 && b[0] == 0 && (b[1] & 0x80) == 0 {
        b = &b[1..];
    }
    if b.len() > 1 && b[0] == 0 && (b[1] & 0x80) != 0 {
        b = &b[1..]; // required sign byte
    }
    if b.is_empty() || b.len() > 32 {
        return Err(CertError::BadSig);
    }
    *out = [0u8; 32];
    out[32 - b.len()..].copy_from_slice(b);
    Ok(())
}

/// BIT STRING holding an uncompressed P-256 point -> (x, y).
fn point(bs: &[u8], x: &mut [u8; 32], y: &mut [u8; 32]) -> Result<(), CertError> {
    if bs.len() != 66 || bs[0] != 0 || bs[1] != 0x04 {
        return Err(CertError::BadSpki);
    }
    x.copy_from_slice(&bs[2..34]);
    y.copy_from_slice(&bs[34..66]);
    Ok(())
}

/// UTCTime/GeneralizedTime "...Z" -> unix seconds (pure; Howard Hinnant days).
fn time_epoch(tag: u8, v: &[u8]) -> Result<u64, CertError> {
    let (y, rest) = match tag {
        0x17 => {
            // UTCTime YYMMDDHHMMSSZ (13 bytes)
            if v.len() != 13 || v[12] != b'Z' {
                return Err(CertError::BadTime);
            }
            let yy = two(v, 0)? as i64;
            (if yy >= 50 { 1900 + yy } else { 2000 + yy }, &v[2..12])
        }
        0x18 => {
            // GeneralizedTime YYYYMMDDHHMMSSZ (15 bytes)
            if v.len() != 15 || v[14] != b'Z' {
                return Err(CertError::BadTime);
            }
            let y = (two(v, 0)? as i64) * 100 + two(v, 2)? as i64;
            (y, &v[4..14])
        }
        _ => return Err(CertError::BadTime),
    };
    let mo = two(rest, 0)? as i64;
    let d = two(rest, 2)? as i64;
    let hh = two(rest, 4)? as i64;
    let mm = two(rest, 6)? as i64;
    let ss = two(rest, 8)? as i64;
    if mo < 1 || mo > 12 || d < 1 || d > 31 || hh > 23 || mm > 59 || ss > 60 {
        return Err(CertError::BadTime);
    }
    let days = days_from_civil(y, mo as u64 as i64, d);
    Ok((days as u64) * 86400 + (hh as u64) * 3600 + (mm as u64) * 60 + ss as u64)
}

fn two(v: &[u8], i: usize) -> Result<u8, CertError> {
    if v[i] < b'0' || v[i] > b'9' || v[i + 1] < b'0' || v[i + 1] > b'9' {
        return Err(CertError::BadTime);
    }
    Ok((v[i] - b'0') * 10 + (v[i + 1] - b'0'))
}

fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146097 + doe - 719468
}

/// Parsed certificate. Slices borrow the input DER.
pub struct Cert<'a> {
    pub tbs: &'a [u8],
    pub sig_r: [u8; 32],
    pub sig_s: [u8; 32],
    pub spki_x: [u8; 32],
    pub spki_y: [u8; 32],
    pub not_before: u64,
    pub not_after: u64,
    pub is_ca: bool,
    pub key_usage: u8, // first BIT STRING content byte, MSB-first numbering
    pub issuer: &'a [u8],
    pub subject: &'a [u8],
    pub san: Option<&'a [u8]>, // raw GeneralNames (OCTET contents)
}

pub fn parse_cert(der: &[u8]) -> Result<Cert<'_>, CertError> {
    parse_cert_inner(der)
}

fn parse_cert_inner(der: &[u8]) -> Result<Cert<'_>, CertError> {
    let mut top_v: [&[u8]; 4] = [&[]; 4];
    let mut top_r: [&[u8]; 4] = [&[]; 4];
    let n = children(der, 0x30, &mut top_v, &mut top_r).map_err(|_| CertError::BadDer)?;
    if n != 3 {
        return Err(CertError::BadDer);
    }
    let tbs_raw = top_r[0];
    let tbs_val = top_v[0];
    // tbs children: version[0], serial, sigalg, issuer, validity, subject,
    // spki, [extensions [3]]. Allow 7 or 8 children (extensions optional).
    let mut f: [&[u8]; 10] = [&[]; 10];
    let mut fr: [&[u8]; 10] = [&[]; 10];
    let nf = children_of_value(tbs_val, &mut f, &mut fr).map_err(|_| CertError::BadDer)?;
    if nf < 7 || nf > 9 {
        return Err(CertError::BadDer);
    }
    // version [0] EXPLICIT { INTEGER 2 } (v3)
    let (ver, vrest) = read_tlv(fr[0]).ok_or(CertError::BadVersion)?;
    if ver.tag != 0xa0 || !vrest.is_empty() {
        return Err(CertError::BadVersion);
    }
    let (vi, vrest2) = read_tlv(ver.val).ok_or(CertError::BadVersion)?;
    if vi.tag != 0x02 || vi.val.len() != 1 || vi.val[0] != 2 || !vrest2.is_empty() {
        return Err(CertError::BadVersion);
    }
    // serial: skip (any positive INTEGER)
    // sig alg (tbs copy)
    let tbs_sigalg = parse_sigalg(f[2])?;
    let _ = tbs_sigalg;
    // issuer / subject raw (byte compare for chaining)
    let issuer_raw = fr[3];
    let subject_raw = fr[5];
    // validity
    let mut vv: [&[u8]; 4] = [&[]; 4];
    let mut vr: [&[u8]; 4] = [&[]; 4];
    if children_of_value(f[4], &mut vv, &mut vr).ok() != Some(2) {
        return Err(CertError::BadDer);
    }
    let (t0, _) = read_tlv(vr[0]).ok_or(CertError::BadTime)?;
    let (t1, _) = read_tlv(vr[1]).ok_or(CertError::BadTime)?;
    let not_before = time_epoch(t0.tag, t0.val)?;
    let not_after = time_epoch(t1.tag, t1.val)?;
    // spki
    let (spki_x, spki_y) = parse_spki(f[6])?;
    // extensions (optional [3] EXPLICIT)
    let mut is_ca = false;
    let mut key_usage: u8 = 0;
    let mut has_ku = false;
    let mut san: Option<&[u8]> = None;
    for k in 7..nf {
        let (ext, erest) = read_tlv(fr[k]).ok_or(CertError::BadDer)?;
        if ext.tag != 0xa3 || !erest.is_empty() {
            return Err(CertError::BadDer);
        }
        let (seq, srest) = read_tlv(ext.val).ok_or(CertError::BadDer)?;
        if seq.tag != 0x30 || !srest.is_empty() {
            return Err(CertError::BadDer);
        }
        let mut eb = seq.val;
        while !eb.is_empty() {
            let (e, r) = read_tlv(eb).ok_or(CertError::BadDer)?;
            if e.tag != 0x30 {
                return Err(CertError::BadDer);
            }
            let mut ev: [&[u8]; 4] = [&[]; 4];
            let mut er: [&[u8]; 4] = [&[]; 4];
            let ne = children_of_value(e.val, &mut ev, &mut er).map_err(|_| CertError::BadDer)?;
            if ne < 2 || ne > 3 {
                return Err(CertError::BadDer);
            }
            let (oidt, _) = read_tlv(er[0]).ok_or(CertError::BadDer)?;
            if oidt.tag != 0x06 {
                return Err(CertError::BadDer);
            }
            let oid_full = er[0]; // includes tag+len header
            let (critical, val_idx) = if ne == 3 {
                let (bt, br) = read_tlv(er[1]).ok_or(CertError::BadDer)?;
                if bt.tag != 0x01 || bt.val.len() != 1 || !br.is_empty() {
                    return Err(CertError::BadDer);
                }
                (bt.val[0] != 0, 2)
            } else {
                (false, 1)
            };
            let (voct, _) = read_tlv(er[val_idx]).ok_or(CertError::BadDer)?;
            if voct.tag != 0x04 {
                return Err(CertError::BadDer);
            }
            if oid_full == OID_BASIC {
                let (bseq, brest) = read_tlv(voct.val).ok_or(CertError::BadDer)?;
                if bseq.tag != 0x30 || !brest.is_empty() {
                    return Err(CertError::BadDer);
                }
                // [CA [pathlen]] — empty SEQ means CA:false... openssl omits
                // the SEQ contents for CA:FALSE (`3000`); CA:TRUE is
                // `30030101ff`. Absent boolean defaults to false.
                if bseq.val.is_empty() {
                    is_ca = false;
                } else {
                    let (bt, br2) = read_tlv(bseq.val).ok_or(CertError::BadDer)?;
                    if bt.tag != 0x01 || bt.val.len() != 1 {
                        return Err(CertError::BadDer);
                    }
                    is_ca = bt.val[0] != 0;
                    let _ = br2; // optional pathLenConstraint, ignored
                }
            } else if oid_full == OID_KEYUSAGE {
                // value is OCTET{ BIT STRING }; unwrap one layer, then the
                // first content byte is the unused-bits count (MSB-first
                // numbering: digitalSignature = 0x80 of the value byte).
                // Single-byte scope only (our recipe emits exactly that).
                let (kbt, krest) = read_tlv(voct.val).ok_or(CertError::BadDer)?;
                if kbt.tag != 0x03 || kbt.val.len() != 2 || !krest.is_empty() {
                    return Err(CertError::BadDer);
                }
                if kbt.val[0] > 7 {
                    return Err(CertError::BadDer);
                }
                key_usage = kbt.val[1];
                has_ku = true;
            } else if oid_full == OID_SAN {
                let (sseq, srest) = read_tlv(voct.val).ok_or(CertError::BadDer)?;
                if sseq.tag != 0x30 || !srest.is_empty() {
                    return Err(CertError::BadDer);
                }
                san = Some(sseq.val);
            } else if oid_full == OID_EKU || oid_full == OID_SKID || oid_full == OID_AKID {
                // known, unenforced
            } else if critical {
                return Err(CertError::UnknownCriticalExtension);
            }
            eb = r;
        }
    }
    let _ = has_ku;
    // outer signatureAlgorithm must equal the tbs copy (compare raw)
    if top_v[1] != f[2] {
        return Err(CertError::BadSigAlg);
    }
    // signature BIT STRING -> SEQ { r, s }
    let (sbt, _) = read_tlv(top_r[2]).ok_or(CertError::BadSig)?;
    if sbt.tag != 0x03 || sbt.val.is_empty() || sbt.val[0] != 0 {
        return Err(CertError::BadSig);
    }
    let (sseq, srest) = read_tlv(&sbt.val[1..]).ok_or(CertError::BadSig)?;
    if sseq.tag != 0x30 || !srest.is_empty() {
        return Err(CertError::BadSig);
    }
    let mut sv: [&[u8]; 4] = [&[]; 4];
    let mut sr: [&[u8]; 4] = [&[]; 4];
    if children_of_value(sseq.val, &mut sv, &mut sr).ok() != Some(2) {
        return Err(CertError::BadSig);
    }
    let (ri, _) = read_tlv(sr[0]).ok_or(CertError::BadSig)?;
    let (si, _) = read_tlv(sr[1]).ok_or(CertError::BadSig)?;
    if ri.tag != 0x02 || si.tag != 0x02 {
        return Err(CertError::BadSig);
    }
    let mut sig_r = [0u8; 32];
    let mut sig_s = [0u8; 32];
    int32(ri.val, &mut sig_r)?;
    int32(si.val, &mut sig_s)?;
    Ok(Cert {
        tbs: tbs_raw,
        sig_r,
        sig_s,
        spki_x,
        spki_y,
        not_before,
        not_after,
        is_ca,
        key_usage,
        issuer: issuer_raw,
        subject: subject_raw,
        san,
    })
}

/// AlgorithmIdentifier must be ecdsa-with-SHA256 (+ optional NULL params).
fn parse_sigalg(v: &[u8]) -> Result<(), CertError> {
    let mut cv: [&[u8]; 4] = [&[]; 4];
    let mut cr: [&[u8]; 4] = [&[]; 4];
    let n = children_of_value(v, &mut cv, &mut cr).map_err(|_| CertError::BadSigAlg)?;
    if n < 1 || n > 2 {
        return Err(CertError::BadSigAlg);
    }
    let (ot, _) = read_tlv(cr[0]).ok_or(CertError::BadSigAlg)?;
    if ot.tag != 0x06 || cr[0] != OID_ECDSA_SHA256 {
        return Err(CertError::BadSigAlg);
    }
    if n == 2 {
        // params: NULL or absent (openssl emits absent; tolerate NULL)
        let (pt, _) = read_tlv(cr[1]).ok_or(CertError::BadSigAlg)?;
        if pt.tag != 0x05 || !pt.val.is_empty() {
            return Err(CertError::BadSigAlg);
        }
    }
    Ok(())
}

/// SubjectPublicKeyInfo -> P-256 (x, y).
fn parse_spki(v: &[u8]) -> Result<([u8; 32], [u8; 32]), CertError> {
    let mut cv: [&[u8]; 4] = [&[]; 4];
    let mut cr: [&[u8]; 4] = [&[]; 4];
    if children_of_value(v, &mut cv, &mut cr).ok() != Some(2) {
        return Err(CertError::BadSpki);
    }
    // alg SEQ { id-ecPublicKey, secp256r1 }
    let mut av: [&[u8]; 4] = [&[]; 4];
    let mut ar: [&[u8]; 4] = [&[]; 4];
    if children_of_value(cv[0], &mut av, &mut ar).ok() != Some(2) {
        return Err(CertError::BadSpki);
    }
    let (o1, _) = read_tlv(ar[0]).ok_or(CertError::BadSpki)?;
    let (o2, _) = read_tlv(ar[1]).ok_or(CertError::BadSpki)?;
    if o1.tag != 0x06 || ar[0] != OID_EC_PUBKEY || o2.tag != 0x06 || ar[1] != OID_SECP256R1 {
        return Err(CertError::BadSpki);
    }
    let (bt, _) = read_tlv(cr[1]).ok_or(CertError::BadSpki)?;
    if bt.tag != 0x03 {
        return Err(CertError::BadSpki);
    }
    let mut x = [0u8; 32];
    let mut y = [0u8; 32];
    point(bt.val, &mut x, &mut y)?;
    // The point must be on the curve (fail closed on twist/degenerate keys).
    let fx = F256::from_be(&x);
    let fy = F256::from_be(&y);
    if !super::p256::on_curve(&fx, &fy) {
        return Err(CertError::BadSpki);
    }
    Ok((x, y))
}

/// Raw ECDSA verify over (signer Q, tbs bytes, r, s): SHA-256(tbs) + n256.
pub fn verify_sig(signer_x: &[u8; 32], signer_y: &[u8; 32], tbs: &[u8], r: &[u8; 32], s: &[u8; 32]) -> bool {
    let mut h = Sha256::new();
    h.update(tbs);
    let digest = h.finalize();
    ecdsa_verify_raw(signer_x, signer_y, &digest, r, s)
}

/// Full chain check: leaf signed by root; root self-signed + CA;
/// validity window; SAN IP match. `now` = guest wall secs.
/// Validity slop ±86400 (test-grade clock honesty, spec §1).
pub fn verify_chain(leaf_der: &[u8], root_der: &[u8], now: u64, expect_ip: [u8; 4]) -> Result<(), CertError> {
    let leaf = parse_cert(leaf_der)?;
    let root = parse_cert(root_der)?;
    if leaf.is_ca {
        return Err(CertError::NotCa);
    }
    if !root.is_ca {
        return Err(CertError::NotCa);
    }
    // keyUsage enforcement (only when the extension is present):
    // digitalSignature = bit0 = 0x80; keyCertSign = bit5 = 0x04.
    if leaf.key_usage != 0 && leaf.key_usage & 0x80 == 0 {
        return Err(CertError::BadKeyUsage);
    }
    if root.key_usage != 0 && root.key_usage & 0x04 == 0 {
        return Err(CertError::BadKeyUsage);
    }
    if now + 86400 < leaf.not_before || now > leaf.not_after + 86400 {
        return Err(CertError::BadValidity);
    }
    if now + 86400 < root.not_before || now > root.not_after + 86400 {
        return Err(CertError::BadValidity);
    }
    if leaf.issuer != root.subject {
        return Err(CertError::IssuerMismatch);
    }
    if !san_has_ip(leaf.san, expect_ip) {
        return Err(CertError::SanMismatch);
    }
    // root self-signature, then leaf by root key.
    if !verify_sig(&root.spki_x, &root.spki_y, root.tbs, &root.sig_r, &root.sig_s) {
        return Err(CertError::BadSignature);
    }
    if !verify_sig(&root.spki_x, &root.spki_y, leaf.tbs, &leaf.sig_r, &leaf.sig_s) {
        return Err(CertError::BadSignature);
    }
    Ok(())
}

/// Scan GeneralNames for an iPAddress (tag 0x87) equal to expect_ip.
fn san_has_ip(san: Option<&[u8]>, expect_ip: [u8; 4]) -> bool {
    let mut b = match san {
        Some(v) => v,
        None => return false,
    };
    while !b.is_empty() {
        let (t, r) = match read_tlv(b) {
            Some(v) => v,
            None => return false,
        };
        if t.tag == 0x87 && t.val.len() == 4 && t.val == expect_ip {
            return true;
        }
        b = r;
    }
    false
}

/// Scan GeneralNames for an exact dNSName match.
pub fn san_has_dns(san: Option<&[u8]>, name: &[u8]) -> bool {
    let mut b = match san {
        Some(v) => v,
        None => return false,
    };
    while !b.is_empty() {
        let (t, r) = match read_tlv(b) {
            Some(v) => v,
            None => return false,
        };
        if t.tag == 0x82 && t.val == name {
            return true;
        }
        b = r;
    }
    false
}
